"""Generate the shared task status union from the normative JSON Schema."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
task = json.loads((root / "packages/contracts/schemas/task.schema.json").read_text())
states = task["properties"]["status"]["enum"]
content = "// Generated by scripts/generate-contracts.py; do not edit.\n"
def array(values):
    return "[\n" + "".join("  " + json.dumps(value) + ",\n" for value in values) + "]"

content += "export const statuses = " + array(states) + " as const;\n"
content += "export type Status = (typeof statuses)[number];\n"
avatar=json.loads((root/'packages/contracts/schemas/avatar-state.schema.json').read_text())
content += "export const avatarStates = " + array(avatar['properties']['state']['enum']) + " as const;\n"
content += "export type AvatarState = (typeof avatarStates)[number];\n"
target = root / "apps/desktop/src/contracts.generated.ts"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    assert target.read_text() == content, "Run python scripts/generate-contracts.py"
else:
    target.write_text(content)
